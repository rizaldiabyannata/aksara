import { expect } from "@playwright/test";
import { test, loginTeacher, loginStudent, seed } from "./fixtures";

test("remedial: rilis → kunci ditahan → coba lagi → nilai dibatasi KKM → batal rilis", async ({ page, browser }) => {
  test.setTimeout(90_000);
  const quiz = seed().remedialQuiz;
  await loginTeacher(page);
  await page.goto(`/teacher/quizzes/${quiz.id}`);
  await page.getByRole("button", { name: "Rilis hasil", exact: true }).first().click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Rilis hasil", exact: true }).click();
  await expect(page.getByText("Hasil sudah dibagikan.")).toBeVisible();
  const student = await browser.newPage();
  await loginStudent(student, "100004");
  await student.goto(`/student/quizzes/${quiz.id}/result`);
  await expect(student.getByText("Kamu bisa mencoba lagi", { exact: true })).toBeVisible();
  await expect(student.getByText("Jawaban benar:")).toHaveCount(0);
  await student.getByRole("link", { name: "Coba lagi dari beranda", exact: true }).click();
  await student.getByRole("button", { name: new RegExp(`^(Mulai|Ulangi) ${quiz.title}$`) }).click();
  await student.waitForURL("**/attempt");
  await student.getByRole("radio", { name: "5", exact: true }).check();
  await student.getByRole("button", { name: "Kumpulkan jawaban", exact: true }).click();
  await student.getByRole("alertdialog").getByRole("button", { name: "Kumpulkan", exact: true }).click();
  await expect(student.getByText("Jawabanmu sudah dikumpulkan.").first()).toBeVisible();
  await student.goto(`/student/quizzes/${quiz.id}/result`);
  await expect(student.getByText("75,00", { exact: true }).first()).toBeVisible();
  await expect(student.getByText("Kamu tuntas", { exact: true })).toBeVisible();
  await student.goto("/student");
  await expect(student.getByRole("button", { name: new RegExp(`^(Mulai|Ulangi) ${quiz.title}$`) })).toHaveCount(0);
  await page.reload();
  await page.getByRole("button", { name: "Batalkan rilis", exact: true }).first().click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Batalkan rilis", exact: true }).click();
  await expect(page.getByRole("button", { name: "Rilis hasil", exact: true }).first()).toBeVisible();
  await student.goto(`/student/quizzes/${quiz.id}/result`);
  await expect(student.getByText("Nilaimu belum keluar", { exact: true })).toBeVisible();
  await student.close();
});

test("pengganti: guru memberi alasan, siswa mengulang tanpa memakai jatah baru", async ({ page, browser }) => {
  const quiz = seed().remedialQuiz;
  await loginTeacher(page);
  await page.goto(`/teacher/quizzes/${quiz.id}`);
  await page.getByRole("heading", { name: "Siswa Empat", exact: true }).locator("xpath=ancestor::div[./details]").getByText("Lihat percobaan", { exact: true }).click();
  await page.getByRole("button", { name: /Beri percobaan pengganti untuk Siswa Empat/ }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible();
  await dialog.getByLabel("Alasan", { exact: true }).fill("Koneksi siswa terputus saat ujian.");
  await dialog.getByRole("button", { name: "Beri percobaan pengganti", exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(page.getByText("Menunggu pengganti", { exact: true })).toBeVisible();
  const student = await browser.newPage();
  await loginStudent(student, "100004");
  await student.getByRole("button", { name: new RegExp(`^(Mulai|Ulangi) ${quiz.title}$`) }).click();
  await student.waitForURL("**/attempt");
  await expect(student.getByRole("radio", { name: "5", exact: true })).toBeVisible();
  await student.getByRole("radio", { name: "5", exact: true }).check();
  await student.getByRole("button", { name: "Kumpulkan jawaban", exact: true }).click();
  await student.getByRole("alertdialog").getByRole("button", { name: "Kumpulkan", exact: true }).click();
  await expect(student.getByText("Jawabanmu sudah dikumpulkan.").first()).toBeVisible();
  await page.reload();
  await page.getByRole("heading", { name: "Siswa Empat", exact: true }).locator("xpath=ancestor::div[./details]").getByText("Lihat percobaan", { exact: true }).click();
  await expect(page.getByText("Diganti", { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Siswa Empat", exact: true }).locator("xpath=ancestor::div[./details]")).toContainText("Percobaan 1/2");
  await student.close();
});
